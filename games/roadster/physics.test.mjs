import assert from 'node:assert/strict';
import { newCarState, zeroInput, stepCar } from './physics.ts';
const advance=(s,input,n)=>{for(let i=0;i<n;i++)stepCar(s,input,1/120);return s;};
const idle=advance(newCarState(),zeroInput(),1200);
assert.ok(idle.grounded && Math.abs(idle.vy)<.001,'Suspension settles');
assert.equal(idle.gas,1,'Idle consumes no gas');
const driven=advance(newCarState(),{...zeroInput(),throttle:1},400);
assert.ok(driven.vz>20,'Ground acceleration');
const before=driven.vz;
advance(driven,{...zeroInput(),brake:1},120);
assert.ok(driven.vz<before,'Braking');
const flight=advance(newCarState(),{...zeroInput(),lift:1},100);
assert.ok(flight.y>2 && flight.vy>0 && flight.gas<1,'Gas launch');
advance(flight,{...zeroInput(),stabilize:true},2000);
assert.ok(flight.launched && flight.landings>=1 && !flight.crashed && flight.grounded,'Assisted landing');
const empty=newCarState();empty.y=30;empty.gas=0;empty.grounded=false;
advance(empty,{...zeroInput(),lift:1},1);
assert.ok(empty.vy<0 && empty.gas===0,'Empty tank cannot lift');
for(const s of [idle,driven,flight,empty])for(const v of Object.values(s))if(typeof v==='number')assert.ok(Number.isFinite(v));
console.log('ROADSTER physics regression checks passed.');
